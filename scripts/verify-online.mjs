import assert from 'node:assert/strict';
import { fixture } from './game-fixture.mjs';
import { OnlineDuel } from '../game/online-duel.js';
import { act, damage } from '../game/online-combat.js';
const packets=[];
const g=fixture();
g.network={connected:true,isHost:true,localId:'host',broadcast:p=>packets.push(p),send:p=>packets.push(p),command:()=>Promise.resolve()};
await g.start({mode:'versus'});
const room={host:'host',round:'round-1',rules:{target:10,duration:180},players:{host:{name:'房主',character:'male'},guest:{name:'好友',character:'female'}}};
const d=new OnlineDuel(g,room),a=d.players.host,b=d.players.guest;
a.p=[0,0,1];b.p=[0,0,-3];g.player.group.position.fromArray(a.p);a.protection=b.protection=0;
const before=[...b.p];
d.consume({type:'player',p:[40,0,40],yaw:0,hp:9999},'guest');assert.deepEqual(b.p,before,'teleport must be rejected');
d.consume({type:'player',p:[0,0,-3],yaw:0,hp:9999},'guest');assert.equal(b.hp,120,'guest cannot grant health');
act(d,'guest',{action:'shot',weapon:0,direction:[0,0,-1],from:[0,0,0]});const ammo=b.inventory[0].ammo;
act(d,'guest',{action:'shot',weapon:0,direction:[0,0,-1]});assert.equal(b.inventory[0].ammo,ammo,'fire rate must be enforced');
act(d,'host',{action:'shot',weapon:1,direction:[0,0,-1]});assert.equal(b.hp,0);assert.equal(a.kills,1);assert.equal(b.deaths,1);
act(d,'guest',{action:'heal'});assert.equal(b.hp,0,'dead player cannot heal');
act(d,'host',{action:'shot',weapon:0,direction:[0,0,-1]});assert.equal(a.kills,1,'no duplicate kill');
g.now+=3.1;d.tick(3.1);assert.equal(b.hp,120);assert.equal(b.inventory[1].ammo,5);assert.equal(b.protection,2);
assert.equal(damage(d,b,999,'host'),false,'spawn protection');b.protection=0;b.hp=20;
act(d,'guest',{action:'heal'});assert.equal(b.hp,85);assert.equal(b.medkits,2);
act(d,'guest',{action:'shield'});assert.equal(b.shield,80);damage(d,b,24,'host');assert.equal(b.hp,85);assert.equal(b.shield,56);
b.immunity=0;b.shield=0;a.kills=9;damage(d,b,120,'host');assert.equal(a.kills,10);assert.equal(d.result,'win');assert.equal(g.state.phase,'victory');assert.ok(packets.some(p=>p.type==='pvp-finish'));
g.clearBattle();g.world.dispose();
// The guest renders host state but cannot end the match or grant itself scores.
const guest=fixture();guest.network={connected:true,isHost:false,localId:'guest',send(){},broadcast(){},command:()=>Promise.resolve()};await guest.start({mode:'versus'});
const gd=new OnlineDuel(guest,room);gd.finish();assert.equal(gd.ended,false);
gd.consume({type:'pvp-finish',scores:{host:99,guest:0}},'intruder');assert.equal(gd.ended,false);
gd.consume({type:'pvp-finish',scores:{host:2,guest:2}},'host');assert.equal(gd.result,'draw');assert.equal(guest.state.phase,'victory');
guest.clearBattle();guest.world.dispose();
console.log('Online authority, teleport rejection, fire rate, damage, respawn, abilities, first-to-ten and guest results passed.');
